from transformers import AutoTokenizer, AutoModel, AutoModelForCausalLM, BitsAndBytesConfig, TrainingArguments
from trl import SFTTrainer
from peft import LoraConfig
from google.colab import userdata
import datasets
from datasets import load_dataset, Dataset
import torch
import pandas as pd

print(datasets.__version__)

bnb_config = BitsAndBytesConfig(
    load_in_4bit=True,
    bnb_4bit_compute_dtype=torch.bfloat16,
    bnb_4bit_quant_type="nf4",
    bnb_4bit_use_double_quant=True
)

HF_TOKEN = userdata.get('HF_TOKEN')
device = "cuda" if torch.cuda.is_available() else "cpu"
#model_name = "Salesforce/codegen-2B-multi"
#model_name = "Salesforce/codegen-350M-multi"
#model_name = "Salesforce/codegen-350M-mono"
model_name = "bigcode/starcoder2-3b"

tokenizer = AutoTokenizer.from_pretrained(model_name, token=HF_TOKEN)
model = AutoModelForCausalLM.from_pretrained(model_name, token=HF_TOKEN, quantization_config=bnb_config).to(device)

print(model.get_memory_footprint() / 1024**3)

for name, module in model.named_modules():
    print(name)

model.print_trainable_parameters()

translation_pairs_df = pd.read_csv('/content/java_python_translation_pairs_corrected_5.csv')
display(translation_pairs_df.head())

# Create a dataset for Java translation pairs
java_ds = translation_pairs_df.apply(lambda row: {
    'language': 'java',
    'instruction': row['text'],
    'response': row['java_code']
}, axis=1)

# Create a dataset for Python translation pairs
python_ds = translation_pairs_df.apply(lambda row: {
    'language': 'python',
    'instruction': row['text'],
    'response': row['python_code']
}, axis=1)

java_to_python = translation_pairs_df.apply(lambda row: {
    'language': 'java to python',
    'instruction': row['java_code'],
    'response': row['python_code']
}, axis=1)

python_to_java = translation_pairs_df.apply(lambda row: {
    'language': 'python to java',
    'instruction': row['python_code'],
    'response': row['java_code']
}, axis=1)

java_code_ds = Dataset.from_list(java_ds.to_list())
python_code_ds = Dataset.from_list(python_ds.to_list())
java_to_python_translation_ds = Dataset.from_list(java_to_python.to_list())
python_to_java_translation_ds = Dataset.from_list(python_to_java.to_list())

# Concatenate all four datasets
combined_translation_ds = datasets.concatenate_datasets([
    java_code_ds,
    python_code_ds,
    java_to_python_translation_ds,
    python_to_java_translation_ds
])

print("Combined Translation Dataset:")
print(combined_translation_ds)
print(combined_translation_ds[0]) # Display the first entry to show the format

def format_cust_instruction_repsonse(obj):
    return {
        "text": f"""{obj['language']}

                 ### Instruction
                 {obj['instruction']}

                 ### Response
                 {obj['response']}"""
            }

instr_train_ds = combined_translation_ds.map(format_cust_instruction_repsonse, remove_columns=combined_translation_ds.column_names)

training_args = TrainingArguments(
    output_dir="./starcoder2-python-java-custom",
    num_train_epochs=3,
    per_device_train_batch_size=1,
    gradient_accumulation_steps=16,
    learning_rate=2e-4,
    logging_steps=20,
    save_strategy="epoch",
    bf16=True,
    report_to="none"
)

peft_config = LoraConfig(
    r=16,
    lora_alpha=32,
    lora_dropout=0.05,
    bias="none",
    target_modules=[
        "q_proj",
        "k_proj",
        "v_proj",
        "o_proj"
    ],
    task_type="CAUSAL_LM"
)

trainer = SFTTrainer(
    model=model,
    train_dataset=instr_train_ds,
    processing_class=tokenizer,
    peft_config=peft_config,
    args=training_args
)

trainer.train()
trainer.save_model(
    "/content/starcoder2-python-java-custom-lora"
)

