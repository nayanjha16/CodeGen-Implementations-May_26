import json
import subprocess
import sys
import os

# 1. Paths pointing strictly to Stage 2 assets
GOLD_JSON_PATH = "data/spider/dev.json"
PRED_JSON_PATH = "outputs/stage2_one_shot/stage2_predictions.json" # Target Stage 2

# Isolated temporary staging files so Stage 1 text files stay safe
TMP_GOLD_TXT = "outputs/stage2_one_shot/tmp_gold_stage2.txt"
TMP_PRED_TXT = "outputs/stage2_one_shot/tmp_pred_stage2.txt"
REPORT_PATH = "outputs/stage2_one_shot/evaluation_report_stage2.txt"

# Ensure the stage2 output directory exists
os.makedirs("outputs/stage2_one_shot", exist_ok=True)

print("捷 Reformatting Stage 2 prediction and gold assets for the evaluation parser...")

# 2. Extract and format the Gold Queries
with open(GOLD_JSON_PATH, "r", encoding="utf-8") as f:
    gold_data = json.load(f)

with open(TMP_GOLD_TXT, "w", encoding="utf-8") as f:
    for item in gold_data:
        f.write(f"{item['query']}\t{item['db_id']}\n")

# 3. Extract and format your Model's Stage 2 Predicted Queries
with open(PRED_JSON_PATH, "r", encoding="utf-8") as f:
    pred_data = json.load(f)

with open(TMP_PRED_TXT, "w", encoding="utf-8") as f:
    for item in pred_data:
        # Pulls 'predicted_sql' generated by your Colab notebook
        sql = item.get("predicted_sql", "SELECT *") or "SELECT *"
        # Clean out any trailing newlines from the string to protect the TSV parser rows
        sql = sql.replace("\n", " ").strip()
        f.write(f"{sql}\n")

print("✅ Stage 2 alignment file formats staged successfully!")
print("📊 Launching Official Exact Match (EM) Evaluation Suite for Stage 2...\n")

# 4. Trigger evaluation.py using the exact same python engine
cmd = [
    sys.executable, "evaluation.py",
    "--gold", TMP_GOLD_TXT,
    "--pred", TMP_PRED_TXT,
    "--db", "data/spider/database",
    "--table", "data/spider/tables.json",
    "--etype", "match"
]

# Run the official evaluation script
eval_run = subprocess.run(cmd, capture_output=True, text=True)

# Print the official metrics to your screen
print(eval_run.stdout)

# Write it out to a dedicated Stage 2 report file
with open(REPORT_PATH, "w", encoding="utf-8") as f:
    f.write(eval_run.stdout)

print(f"💾 Official Stage 2 score report written to: {REPORT_PATH}")