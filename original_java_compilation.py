import tempfile
import os
import subprocess

import pandas as pd

df = pd.read_csv('/content/java_python_translation_pairs_corrected_5.csv')
display(df.head())



def check_java_compilation(java_code):
    # Create a temporary directory
    with tempfile.TemporaryDirectory() as tmpdir:
        # Write the Java code to a .java file
        file_path = os.path.join(tmpdir, "Solution.java")
        with open(file_path, "w") as f:
            f.write(java_code)

        # Try to compile the Java file
        try:
            # Use subprocess to run javac
            compile_process = subprocess.run(
                ["javac", file_path],
                capture_output=True,
                text=True,
                check=False # Do not raise an exception for non-zero exit codes
            )
            # If javac returns 0, compilation was successful
            if compile_process.returncode == 0:
                return True
            else:
                # print(f"Compilation error: {compile_process.stderr}")
                return False
        except FileNotFoundError:
            print("Error: javac command not found. Make sure Java Development Kit (JDK) is installed and in your PATH.")
            return False
        except Exception as e:
            print(f"An unexpected error occurred during compilation check: {e}")
            return False

df['java_compiles'] = df['java_code'].apply(check_java_compilation)

compilation_percentage = df['java_compiles'].mean() * 100
print(f"Percentage of Java code that compiles successfully: {compilation_percentage:.2f}%")